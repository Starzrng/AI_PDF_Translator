def register_font() -> str:
    candidates = [
        "/System/Library/Fonts/Supplemental/Arial Unicode.ttf",
        "/Library/Fonts/Arial Unicode.ttf",
        "/System/Library/Fonts/Supplemental/Times New Roman.ttf",
    ]
    for path in candidates:
        if Path(path).exists():
            pdfmetrics.registerFont(TTFont("RuFont", path))
            return "RuFont"
    raise FileNotFoundError("No Cyrillic font found.")


def build_styles(font_name: str):
    styles = getSampleStyleSheet()
    styles.add(
        ParagraphStyle(
            name="RuTitle",
            parent=styles["Heading1"],
            fontName=font_name,
            fontSize=17,
            leading=21,
            textColor=colors.HexColor("#111827"),
            spaceAfter=8,
        )
    )
    styles.add(
        ParagraphStyle(
            name="RuMeta",
            parent=styles["BodyText"],
            fontName=font_name,
            fontSize=8.8,
            leading=11,
            textColor=colors.HexColor("#6b7280"),
            spaceAfter=8,
            alignment=TA_CENTER,
        )
    )
    styles.add(
        ParagraphStyle(
            name="RuBody",
            parent=styles["BodyText"],
            fontName=font_name,
            fontSize=9.5,
            leading=12.5,
            textColor=colors.HexColor("#1f2937"),
            spaceAfter=4,
        )
    )
    styles.add(
        ParagraphStyle(
            name="RuBullet",
            parent=styles["BodyText"],
            fontName=font_name,
            fontSize=9.5,
            leading=12.5,
            textColor=colors.HexColor("#1f2937"),
            leftIndent=14,
            bulletIndent=0,
            spaceAfter=2,
        )
    )
    return styles


def para_from_block(block: str, style: ParagraphStyle) -> Paragraph:
    lines = [escape(line.strip()) for line in block.splitlines() if line.strip()]
    return Paragraph("<br/>".join(lines), style)


def section_pdf(section: dict, styles) -> BytesIO:
    buf = BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=16 * mm,
        rightMargin=16 * mm,
        topMargin=16 * mm,
        bottomMargin=14 * mm,
        title=section["title"],
    )
    story = [
        Paragraph("Русский перевод. Оригинальная страница из руководства сохранена перед этим листом.", styles["RuMeta"]),
        Paragraph(escape(section["title"]), styles["RuTitle"]),
    ]
    blocks = [block.strip() for block in section["body"].strip().split("\n\n") if block.strip()]
    for block in blocks:
        lines = [line.strip() for line in block.splitlines() if line.strip()]
        if lines and all(line.startswith("- ") for line in lines):
            for line in lines:
                story.append(Paragraph(escape(line[2:]), styles["RuBullet"], bulletText="•"))
            story.append(Spacer(1, 1.5 * mm))
        else:
            story.append(para_from_block(block, styles["RuBody"]))
            story.append(Spacer(1, 1.5 * mm))
    doc.build(story)
    buf.seek(0)
    return buf


def main():
    font_name = register_font()
    styles = build_styles(font_name)

    original = PdfReader(str(SOURCE))
    writer = PdfWriter()

    for index, section in enumerate(SECTIONS):
        writer.add_page(original.pages[index])
        translated = PdfReader(section_pdf(section, styles))
        for page in translated.pages:
            writer.add_page(page)

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT.open("wb") as f:
        writer.write(f)

    print(OUTPUT)


if __name__ == "__main__":
    main()
