def page(): return doc.new_page(width=W,height=H)
def html(pg,rect,inner,size=10,color=DK,align="left",lh=1.3):
    pg.insert_htmlbox(fitz.Rect(rect),
        f'<div style="font-size:{size}px;color:{color};text-align:{align};line-height:{lh};font-family:ar">{inner}</div>',
        archive=arch,css=CSS)
def hbar(pg,num,title,y=M):
    r=fitz.Rect(M,y,W-M,y+30); pg.draw_rect(r,color=None,fill=GREENC)
    html(pg,(M+14,y+6,W-M,y+30),f'<b>{num}&nbsp;&nbsp;{title}</b>',15,"#ffffff","left")
    return y+30
def imgrect(pg,img,y,maxh=300):
    pix=fitz.Pixmap(img); iw,ih=pix.width,pix.height
    sc=min((W-2*M)/iw, maxh/ih); dw,dh=iw*sc,ih*sc; x0=(W-dw)/2
    pg.insert_image(fitz.Rect(x0,y,x0+dw,y+dh), filename=img); return y+dh
def img_legend(img, legend, num=None, title=None, maxh=300, lsize=9, lh=1.4):
    p=page(); y=M
    if title: y=hbar(p,num,title)+12
    y=imgrect(p,img,y,maxh)
    html(p,(M,y+10,W-M,H-26), legend, lsize, DK,"left",lh)
    return p

